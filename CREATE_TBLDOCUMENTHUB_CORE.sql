IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'tbldocumentlabelset')
BEGIN
    CREATE TABLE tbldocumentlabelset (
        DocumentLabelSetId INT IDENTITY(1,1) PRIMARY KEY,
        LabelSetName NVARCHAR(200) NOT NULL,
        LabelSetDescription NVARCHAR(2000) NULL,
        IsActive BIT NOT NULL CONSTRAINT DF_tbldocumentlabelset_IsActive DEFAULT (1),
        CreatedByUserId INT NULL,
        CreatedDate DATETIME2 NOT NULL CONSTRAINT DF_tbldocumentlabelset_CreatedDate DEFAULT (SYSUTCDATETIME()),
        UpdatedByUserId INT NULL,
        UpdatedDate DATETIME2 NULL
    );
END;
GO

IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'tbldocumentclassificationlabel')
BEGIN
    CREATE TABLE tbldocumentclassificationlabel (
        DocumentClassificationLabelId INT IDENTITY(1,1) PRIMARY KEY,
        DocumentLabelSetId INT NOT NULL,
        ClassificationLabel NVARCHAR(80) NOT NULL,
        ClassificationDescription NVARCHAR(2000) NULL,
        ClassificationPrompt NVARCHAR(MAX) NOT NULL,
        SeedDocumentName NVARCHAR(260) NULL,
        SeedDocumentHash NVARCHAR(128) NULL,
        IsAutoGenerated BIT NOT NULL CONSTRAINT DF_tbldocumentclassificationlabel_IsAutoGenerated DEFAULT (1),
        IsActive BIT NOT NULL CONSTRAINT DF_tbldocumentclassificationlabel_IsActive DEFAULT (1),
        CreatedByUserId INT NULL,
        CreatedDate DATETIME2 NOT NULL CONSTRAINT DF_tbldocumentclassificationlabel_CreatedDate DEFAULT (SYSUTCDATETIME()),
        UpdatedByUserId INT NULL,
        UpdatedDate DATETIME2 NULL,
        CONSTRAINT FK_tbldocumentclassificationlabel_tbldocumentlabelset
            FOREIGN KEY (DocumentLabelSetId) REFERENCES tbldocumentlabelset(DocumentLabelSetId)
    );

    CREATE INDEX IX_tbldocumentclassificationlabel_DocumentLabelSetId
        ON tbldocumentclassificationlabel (DocumentLabelSetId);
END;
GO

