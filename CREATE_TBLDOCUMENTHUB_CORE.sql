IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'tbldocumentprocessingrun')
BEGIN
    CREATE TABLE tbldocumentprocessingrun (
        DocumentProcessingRunId BIGINT IDENTITY(1,1) PRIMARY KEY,
        SourceModule NVARCHAR(100) NULL,
        SourceRecordId NVARCHAR(120) NULL,
        UploadedFileName NVARCHAR(260) NOT NULL,
        UploadedFileHash NVARCHAR(128) NULL,
        ProcessingType NVARCHAR(50) NOT NULL, -- classification | summarisation | extraction
        AssetType NVARCHAR(50) NOT NULL,      -- label-set | summarisation-template | extraction-template
        AssetId INT NOT NULL,
        ResultJson NVARCHAR(MAX) NULL,
        ConfidenceScore DECIMAL(5,4) NULL,
        Status NVARCHAR(40) NOT NULL CONSTRAINT DF_tbldocumentprocessingrun_Status DEFAULT ('Completed'),
        CreatedByUserId INT NULL,
        CreatedDate DATETIME2 NOT NULL CONSTRAINT DF_tbldocumentprocessingrun_CreatedDate DEFAULT (SYSUTCDATETIME())
    );

    CREATE INDEX IX_tbldocumentprocessingrun_AssetType_AssetId
        ON tbldocumentprocessingrun (AssetType, AssetId);
END;
GO

